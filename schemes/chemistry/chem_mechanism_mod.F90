module chem_mechanism_mod
!---------------------------------------------------------------------
! Descriptor of the active gas-phase chemistry mechanism.
!
! A mechanism package generated by the CAM chemistry preprocessor
! (model = cam_sima) fills one chem_mechanism_t with the sizes and name
! tables that CAM keeps in chem_mods and mo_tracname, plus procedure
! pointers to the generated kernels. Chemistry schemes read the
! descriptor and never `use` a package module directly, so several
! packages can be compiled into one executable and the chem_mechanism
! namelist variable picks one at run time.
!
! The descriptor is protected module state rather than a CCPP argument:
! capgen cannot pass a derived type with procedure-pointer components,
! and the register phase can only return constituents.
!
! The kernel interfaces use explicit-shape dummies dimensioned by dummy
! integers so that every package presents identical characteristics.
! Callers pass max(1, size) extents exactly as CAM's driver does; the
! vector kernels rely on sequence association of (ncol,nlev,...) actuals
! onto their (ncol*nlev,...) work arrays.
!---------------------------------------------------------------------
  use ccpp_kinds, only: kind_phys

  implicit none
  private

  public :: chem_mechanism_t
  public :: chem_mechanism_define_i
  public :: chem_mechanism_activate
  public :: chem_mechanism_is_active
  public :: chem_mechanism_reset
  public :: mech

  integer, parameter, public :: chem_mech_name_len = 32
  integer, parameter, public :: chem_spc_name_len  = 16
  integer, parameter, public :: chem_rxt_tag_len   = 32

  abstract interface
     ! Temperature and density dependent rate constants (mo_setrxt)
     subroutine setrxt_i( ncol, nlev, nrxt, rate, temp, m )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nrxt
       real(kind_phys), intent(inout) :: rate(ncol,nlev,nrxt)
       real(kind_phys), intent(in)    :: temp(ncol,nlev)
       real(kind_phys), intent(in)    :: m(ncol,nlev)
     end subroutine setrxt_i

     ! Rate constants restricted to levels 1:kbot (WACCM heating rates)
     subroutine setrxt_hrates_i( ncol, nlev, nrxt, kbot, rate, temp, m )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nrxt, kbot
       real(kind_phys), intent(inout) :: rate(ncol,nlev,nrxt)
       real(kind_phys), intent(in)    :: temp(ncol,nlev)
       real(kind_phys), intent(in)    :: m(ncol,nlev)
     end subroutine setrxt_hrates_i

     ! Fold invariant densities into the rate constants (mo_adjrxt)
     subroutine adjrxt_i( ncol, nlev, nrxt, ninv, rate, inv, m )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nrxt, ninv
       real(kind_phys), intent(inout) :: rate(ncol,nlev,nrxt)
       real(kind_phys), intent(in)    :: inv(ncol,nlev,ninv)
       real(kind_phys), intent(in)    :: m(ncol,nlev)
     end subroutine adjrxt_i

     ! Fold invariant densities into the photolysis rates (mo_phtadj)
     subroutine phtadj_i( ncol, nlev, nphot, ninv, p_rate, inv, m )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nphot, ninv
       real(kind_phys), intent(inout) :: p_rate(ncol,nlev,nphot)
       real(kind_phys), intent(in)    :: inv(ncol,nlev,ninv)
       real(kind_phys), intent(in)    :: m(ncol,nlev)
     end subroutine phtadj_i

     ! Reaction rates from rate constants and concentrations (mo_rxt_rates_conv)
     subroutine set_rates_i( ncol, nlev, nrxt, nspc, rxt_rates, sol )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nrxt, nspc
       real(kind_phys), intent(inout) :: rxt_rates(ncol,nlev,nrxt)
       real(kind_phys), intent(in)    :: sol(ncol,nlev,nspc)
     end subroutine set_rates_i

     ! Implicit solver tolerances; call once after the descriptor is filled
     subroutine imp_slv_inti_i()
     end subroutine imp_slv_inti_i

     ! Implicit (Newton-Raphson backward Euler) solver (mo_imp_sol)
     subroutine imp_sol_i( ncol, nlev, nspc, nrxt, nextfrc, ncls, base_sol, reaction_rates, &
                           het_rates, extfrc, delt, prod_out, loss_out, nfail_step, nfail_cell )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nspc, nrxt, nextfrc, ncls
       real(kind_phys), intent(inout) :: base_sol(ncol,nlev,nspc)
       real(kind_phys), intent(in)    :: reaction_rates(ncol,nlev,nrxt)
       real(kind_phys), intent(in)    :: het_rates(ncol,nlev,nspc)
       real(kind_phys), intent(in)    :: extfrc(ncol,nlev,nextfrc)
       real(kind_phys), intent(in)    :: delt
       real(kind_phys), intent(out)   :: prod_out(ncol,nlev,ncls)
       real(kind_phys), intent(out)   :: loss_out(ncol,nlev,ncls)
       integer,         intent(out)   :: nfail_step, nfail_cell
     end subroutine imp_sol_i

     ! Explicit (forward Euler) solver below the chemistry tropopause (mo_exp_sol)
     subroutine exp_sol_i( ncol, nlev, nspc, nrxt, nextfrc, ncls, base_sol, reaction_rates, &
                           het_rates, extfrc, delt, ltrop, prod_out, loss_out )
       import :: kind_phys
       integer,         intent(in)    :: ncol, nlev, nspc, nrxt, nextfrc, ncls
       real(kind_phys), intent(inout) :: base_sol(ncol,nlev,nspc)
       real(kind_phys), intent(in)    :: reaction_rates(ncol,nlev,nrxt)
       real(kind_phys), intent(in)    :: het_rates(ncol,nlev,nspc)
       real(kind_phys), intent(in)    :: extfrc(ncol,nlev,nextfrc)
       real(kind_phys), intent(in)    :: delt
       integer,         intent(in)    :: ltrop(ncol)
       real(kind_phys), intent(out)   :: prod_out(ncol,nlev,ncls)
       real(kind_phys), intent(out)   :: loss_out(ncol,nlev,ncls)
     end subroutine exp_sol_i
  end interface

  type :: chem_mechanism_t
     character(len=chem_mech_name_len) :: name = ''
     logical :: is_vector = .false.
     integer :: veclen    = 1     ! vector block length (1 for the scalar solver)
     integer :: nspecies  = 0     ! solution species (gas_pcnst)
     integer :: nslvd     = 0     ! short-lived, not advected, species
     integer :: nrxt      = 0     ! reactions (rxntot); photolysis occupies slots 1:nphot
     integer :: nphot     = 0     ! photolysis reactions
     integer :: ninv      = 0     ! invariant species (nfs)
     integer :: nextfrc   = 0     ! externally forced species (extcnt)
     integer :: nexplicit = 0     ! explicit-class species (clscnt1)
     integer :: nimplicit = 0     ! implicit-class species (clscnt4)
     integer :: nzcnt     = 0     ! non-zero Jacobian entries
     integer :: indexm    = 0     ! invariant index of total density
     integer :: indexh2o  = 0     ! invariant index of water vapor (0 if none)
     integer :: nrxt_tag  = 0     ! tagged reactions
     integer :: ncph      = 0     ! reactions with chemical potential heating
     character(len=chem_spc_name_len), allocatable :: species(:)          ! solsym
     character(len=chem_spc_name_len), allocatable :: slvd(:)             ! short-lived names
     character(len=chem_spc_name_len), allocatable :: invariants(:)       ! inv_lst
     character(len=chem_spc_name_len), allocatable :: extfrc(:)           ! extfrc_lst
     logical,                          allocatable :: frc_from_dataset(:)
     real(kind_phys),                  allocatable :: adv_mass(:)         ! g mol-1
     real(kind_phys),                  allocatable :: crb_mass(:)         ! carbon mass, g mol-1
     real(kind_phys),                  allocatable :: fix_mass(:)         ! invariant masses, g mol-1
     character(len=chem_rxt_tag_len),  allocatable :: rxt_tag(:)          ! rxt_tag_lst
     integer,                          allocatable :: rxt_tag_map(:)      ! tag -> reaction index
     character(len=chem_spc_name_len), allocatable :: pht_alias(:,:)      ! (nphot,2)
     real(kind_phys),                  allocatable :: pht_alias_mult(:,:) ! (nphot,2)
     integer,                          allocatable :: cph_rid(:)
     real(kind_phys),                  allocatable :: cph_enthalpy(:)
     integer,                          allocatable :: num_rnts(:)         ! reactant count per gas-phase reaction
     integer,                          allocatable :: clsmap(:,:)         ! (nspecies,5): class member -> species
     integer                                       :: clscnt(5) = 0
     integer                                       :: cls_rxt_cnt(4,5) = 0
     procedure(setrxt_i),        pointer, nopass :: setrxt        => null()
     procedure(setrxt_hrates_i), pointer, nopass :: setrxt_hrates => null()
     procedure(adjrxt_i),        pointer, nopass :: adjrxt        => null()
     procedure(phtadj_i),        pointer, nopass :: phtadj        => null()
     procedure(set_rates_i),     pointer, nopass :: set_rates     => null()
     procedure(imp_slv_inti_i),  pointer, nopass :: imp_slv_inti  => null()
     procedure(imp_sol_i),       pointer, nopass :: imp_sol       => null()
     procedure(exp_sol_i),       pointer, nopass :: exp_sol       => null()
   contains
     procedure :: spc_ndx        => chem_mech_spc_ndx
     procedure :: inv_ndx        => chem_mech_inv_ndx
     procedure :: extfrc_ndx     => chem_mech_extfrc_ndx
     procedure :: rxt_ndx        => chem_mech_rxt_ndx
     procedure :: is_short_lived => chem_mech_is_short_lived
  end type chem_mechanism_t

  abstract interface
     ! The single public routine of a generated <mech>_chem_mechanism module
     subroutine chem_mechanism_define_i( mech, errmsg, errflg )
       import :: chem_mechanism_t
       type(chem_mechanism_t), intent(inout) :: mech
       character(len=*),       intent(out)   :: errmsg
       integer,                intent(out)   :: errflg
     end subroutine chem_mechanism_define_i
  end interface

  ! The active mechanism, filled at the register phase by the selected package
  type(chem_mechanism_t), protected, save :: mech

contains

  !-------------------------------------------------------------------
  ! Fill the descriptor from a package and build its constituent list.
  ! Every solution species except H2O becomes a constituent named after
  ! the CAM species name; H2O maps to the host water vapor constituent.
  ! Aerosol species that MAM also registers are accepted by the
  ! framework because units and flags agree; the molar mass is not
  ! compared by the framework, so the species-map scheme cross-checks it.
  ! Aerosol number species (num_a*, the rule CAM's chem_register uses)
  ! are number mixing ratios in kg-1, as mam_constituents registers them;
  ! their mechanism mass is the placeholder 1.0074 g mol-1 that
  ! mam_constituents also registers.
  !-------------------------------------------------------------------
  subroutine chem_mechanism_activate( name, define, constituent_props, errmsg, errflg )
    use ccpp_constituent_prop_mod, only: ccpp_constituent_properties_t
    use ccpp_chem_utils,           only: chem_constituent_qmin, chem_molar_mass_kgmol

    character(len=*),                     intent(in)  :: name
    procedure(chem_mechanism_define_i)                :: define
    type(ccpp_constituent_properties_t), allocatable, intent(out) :: constituent_props(:)
    character(len=*),                     intent(out) :: errmsg
    integer,                              intent(out) :: errflg

    integer :: m, n, ncnst
    character(len=16) :: units, kind_of_ratio

    errmsg = ''
    errflg = 0

    if( len_trim( mech%name ) > 0 ) then
       errflg = 1
       errmsg = 'chem_mechanism_activate: mechanism ' // trim( mech%name ) // &
            ' is already active; cannot also activate ' // trim( name ) // &
            '. The chem_mechanism namelist variable selects exactly one.'
       return
    end if

    call define( mech, errmsg, errflg )
    if( errflg /= 0 ) return

    if( trim( mech%name ) /= trim( name ) ) then
       errflg = 1
       errmsg = 'chem_mechanism_activate: package ' // trim( mech%name ) // &
            ' was activated under the name ' // trim( name )
       return
    end if

    ncnst = 0
    do m = 1, mech%nspecies
       if( .not. is_water( mech%species(m) ) ) ncnst = ncnst + 1
    end do
    allocate( constituent_props(ncnst) )

    n = 0
    do m = 1, mech%nspecies
       if( is_water( mech%species(m) ) ) cycle
       n = n + 1
       if( is_number( mech%species(m) ) ) then
          units = 'kg-1'
          kind_of_ratio = 'number'
       else
          units = 'kg kg-1'
          kind_of_ratio = 'mass'
       end if
       call constituent_props(n)%instantiate( &
            std_name          = trim( mech%species(m) ), &
            long_name         = trim( kind_of_ratio ) // ' mixing ratio ' // trim( mech%species(m) ), &
            diag_name         = trim( mech%species(m) ), &
            units             = trim( units ), &
            vertical_dim      = 'vertical_layer_dimension', &
            advected          = .not. mech%is_short_lived( mech%species(m) ), &
            min_value         = chem_constituent_qmin( trim( mech%species(m) ) ), &
            ! g/mol -> kg/mol preserving the *1e3 round trip bitwise
            molar_mass        = chem_molar_mass_kgmol( mech%adv_mass(m) ), &
            mixing_ratio_type = 'dry', &
            errcode           = errflg, &
            errmsg            = errmsg )
       if( errflg /= 0 ) return
    end do

  end subroutine chem_mechanism_activate

  logical function chem_mechanism_is_active()
    chem_mechanism_is_active = len_trim( mech%name ) > 0
  end function chem_mechanism_is_active

  ! Forget the active mechanism (unit tests that activate several in turn)
  subroutine chem_mechanism_reset()
    type(chem_mechanism_t) :: empty
    mech = empty
  end subroutine chem_mechanism_reset

  logical function is_water( name )
    character(len=*), intent(in) :: name
    is_water = trim( name ) == 'H2O'
  end function is_water

  ! Aerosol number species, by CAM's naming rule for the chemistry solution set
  logical function is_number( name )
    character(len=*), intent(in) :: name
    is_number = name(1:min(5, len(name))) == 'num_a'
  end function is_number

  !-------------------------------------------------------------------
  ! Name lookups, the mo_chem_utls queries: index or 0 when absent
  !-------------------------------------------------------------------
  integer function chem_mech_spc_ndx( this, spc_name, ignore_case ) result( ndx )
    use atmos_phys_string_utils, only: to_upper
    class(chem_mechanism_t), intent(in) :: this
    character(len=*),        intent(in) :: spc_name
    logical, optional,       intent(in) :: ignore_case

    integer :: m
    logical :: fold

    fold = .false.
    if( present( ignore_case ) ) fold = ignore_case
    ndx = 0
    do m = 1, this%nspecies
       if( fold ) then
          if( to_upper( trim( spc_name ) ) == to_upper( trim( this%species(m) ) ) ) then
             ndx = m
             exit
          end if
       else
          if( trim( spc_name ) == trim( this%species(m) ) ) then
             ndx = m
             exit
          end if
       end if
    end do
  end function chem_mech_spc_ndx

  integer function chem_mech_inv_ndx( this, inv_name ) result( ndx )
    class(chem_mechanism_t), intent(in) :: this
    character(len=*),        intent(in) :: inv_name
    integer :: m
    ndx = 0
    do m = 1, this%ninv
       if( trim( inv_name ) == trim( this%invariants(m) ) ) then
          ndx = m
          exit
       end if
    end do
  end function chem_mech_inv_ndx

  integer function chem_mech_extfrc_ndx( this, frc_name ) result( ndx )
    class(chem_mechanism_t), intent(in) :: this
    character(len=*),        intent(in) :: frc_name
    integer :: m
    ndx = 0
    do m = 1, this%nextfrc
       if( trim( frc_name ) == trim( this%extfrc(m) ) ) then
          ndx = m
          exit
       end if
    end do
  end function chem_mech_extfrc_ndx

  ! Reaction index of a tag, 0 when absent (rxt_tag_map resolves the slot)
  integer function chem_mech_rxt_ndx( this, tag ) result( ndx )
    class(chem_mechanism_t), intent(in) :: this
    character(len=*),        intent(in) :: tag
    integer :: m
    ndx = 0
    do m = 1, this%nrxt_tag
       if( trim( tag ) == trim( this%rxt_tag(m) ) ) then
          ndx = this%rxt_tag_map(m)
          exit
       end if
    end do
  end function chem_mech_rxt_ndx

  logical function chem_mech_is_short_lived( this, spc_name ) result( slvd )
    class(chem_mechanism_t), intent(in) :: this
    character(len=*),        intent(in) :: spc_name
    integer :: m
    slvd = .false.
    do m = 1, this%nslvd
       if( trim( spc_name ) == trim( this%slvd(m) ) ) then
          slvd = .true.
          exit
       end if
    end do
  end function chem_mech_is_short_lived

end module chem_mechanism_mod
