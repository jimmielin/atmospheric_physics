module trop_mam4_chem_mechanism
!---------------------------------------------------------------------
! Generated by the CAM chemistry preprocessor (model = cam_sima). Do not edit.
! Plugin interface of the trop_mam4 mechanism: fills a chem_mechanism_t
! descriptor from the generated tables and exposes the generated kernels
! through wrappers whose dummy arguments are dimensioned by dummy
! integers, so that one abstract interface fits every mechanism.
!---------------------------------------------------------------------
  use ccpp_kinds, only: kind_phys

  implicit none
  private

  public :: trop_mam4_chem_mechanism_define

contains

  subroutine trop_mam4_chem_mechanism_define( mech, errmsg, errflg )
    use chem_mechanism_mod, only: chem_mechanism_t
    use trop_mam4_chem_mods, only: gas_pcnst, nslvd, rxntot, phtcnt, nfs, extcnt, clscnt1, clscnt4
    use trop_mam4_chem_mods, only: nzcnt, indexm, indexh2o, rxt_tag_cnt, enthalpy_cnt
    use trop_mam4_chem_mods, only: solsym, adv_mass, crb_mass, fix_mass, inv_lst, extfrc_lst, slvd_lst
    use trop_mam4_chem_mods, only: frc_from_dataset, clscnt, cls_rxt_cnt, clsmap
    use trop_mam4_chem_mods, only: rxt_tag_lst, rxt_tag_map, pht_alias_lst, pht_alias_mult
    use trop_mam4_chem_mods, only: cph_rid, cph_enthalpy, num_rnts
    use trop_mam4_mo_sim_dat, only: set_sim_dat

    type(chem_mechanism_t), intent(inout) :: mech
    character(len=*),       intent(out)   :: errmsg
    integer,                intent(out)   :: errflg

    errmsg = ''
    errflg = 0
    call set_sim_dat( errmsg, errflg )
    if( errflg /= 0 ) return

    mech%name      = 'trop_mam4'
    mech%is_vector = .false.
    mech%veclen    = 1
    mech%nspecies  = gas_pcnst
    mech%nslvd     = nslvd
    mech%nrxt      = rxntot
    mech%nphot     = phtcnt
    mech%ninv      = nfs
    mech%nextfrc   = extcnt
    mech%nexplicit = clscnt1
    mech%nimplicit = clscnt4
    mech%nzcnt     = nzcnt
    mech%indexm    = indexm
    mech%indexh2o  = indexh2o
    mech%nrxt_tag  = rxt_tag_cnt
    mech%ncph      = enthalpy_cnt

    mech%species    = solsym(:gas_pcnst)
    mech%adv_mass   = adv_mass(:gas_pcnst)
    mech%crb_mass   = crb_mass(:gas_pcnst)
    mech%slvd       = slvd_lst(:nslvd)
    mech%invariants = inv_lst(:nfs)
    mech%fix_mass   = fix_mass(:nfs)
    mech%extfrc     = extfrc_lst(:extcnt)
    mech%frc_from_dataset = frc_from_dataset(:extcnt)
    mech%clscnt      = clscnt
    mech%cls_rxt_cnt = cls_rxt_cnt
    mech%clsmap      = clsmap

    ! set_sim_dat allocates these tables only when they are not empty
    if( allocated( rxt_tag_lst ) ) then
       mech%rxt_tag     = rxt_tag_lst
       mech%rxt_tag_map = rxt_tag_map
    else
       allocate( mech%rxt_tag(0), mech%rxt_tag_map(0) )
    end if
    if( allocated( pht_alias_lst ) ) then
       mech%pht_alias      = pht_alias_lst
       mech%pht_alias_mult = pht_alias_mult
    else
       allocate( mech%pht_alias(0,2), mech%pht_alias_mult(0,2) )
    end if
    if( allocated( cph_rid ) ) then
       mech%cph_rid      = cph_rid
       mech%cph_enthalpy = cph_enthalpy
    else
       allocate( mech%cph_rid(0), mech%cph_enthalpy(0) )
    end if
    if( allocated( num_rnts ) ) then
       mech%num_rnts = num_rnts
    else
       allocate( mech%num_rnts(0) )
    end if

    mech%setrxt        => setrxt_w
    mech%setrxt_hrates => setrxt_hrates_w
    mech%adjrxt        => adjrxt_w
    mech%phtadj        => phtadj_w
    mech%set_rates     => set_rates_w
    mech%imp_slv_inti  => imp_slv_inti_w
    mech%imp_sol       => imp_sol_w
    mech%exp_sol       => exp_sol_w

  end subroutine trop_mam4_chem_mechanism_define

  !--------------------------------------------------------------------
  ! Kernel wrappers. The generated kernels dimension their arrays with
  ! the package constants; the caller passes the same extents through
  ! the descriptor sizes, and the explicit-shape actuals are passed on
  ! by sequence association (the vector kernels flatten ncol*nlev).
  !--------------------------------------------------------------------

  subroutine setrxt_w( ncol, nlev, nrxt, rate, temp, m )
    use trop_mam4_mo_setrxt, only: setrxt
    integer,         intent(in)    :: ncol, nlev, nrxt
    real(kind_phys), intent(inout) :: rate(ncol,nlev,nrxt)
    real(kind_phys), intent(in)    :: temp(ncol,nlev)
    real(kind_phys), intent(in)    :: m(ncol,nlev)
    call setrxt( rate, temp, m, ncol, nlev )
  end subroutine setrxt_w

  subroutine setrxt_hrates_w( ncol, nlev, nrxt, kbot, rate, temp, m )
    use trop_mam4_mo_setrxt, only: setrxt_hrates
    integer,         intent(in)    :: ncol, nlev, nrxt, kbot
    real(kind_phys), intent(inout) :: rate(ncol,nlev,nrxt)
    real(kind_phys), intent(in)    :: temp(ncol,nlev)
    real(kind_phys), intent(in)    :: m(ncol,nlev)
    call setrxt_hrates( rate, temp, m, ncol, kbot, nlev )
  end subroutine setrxt_hrates_w

  subroutine adjrxt_w( ncol, nlev, nrxt, ninv, rate, inv, m )
    use trop_mam4_mo_adjrxt, only: adjrxt
    integer,         intent(in)    :: ncol, nlev, nrxt, ninv
    real(kind_phys), intent(inout) :: rate(ncol,nlev,nrxt)
    real(kind_phys), intent(in)    :: inv(ncol,nlev,ninv)
    real(kind_phys), intent(in)    :: m(ncol,nlev)
    call adjrxt( rate, inv, m, ncol, nlev )
  end subroutine adjrxt_w

  subroutine phtadj_w( ncol, nlev, nphot, ninv, p_rate, inv, m )
    use trop_mam4_mo_phtadj, only: phtadj
    integer,         intent(in)    :: ncol, nlev, nphot, ninv
    real(kind_phys), intent(inout) :: p_rate(ncol,nlev,nphot)
    real(kind_phys), intent(in)    :: inv(ncol,nlev,ninv)
    real(kind_phys), intent(in)    :: m(ncol,nlev)
    call phtadj( p_rate, inv, m, ncol, nlev )
  end subroutine phtadj_w

  subroutine set_rates_w( ncol, nlev, nrxt, nspc, rxt_rates, sol )
    use trop_mam4_mo_rxt_rates_conv, only: set_rates
    integer,         intent(in)    :: ncol, nlev, nrxt, nspc
    real(kind_phys), intent(inout) :: rxt_rates(ncol,nlev,nrxt)
    real(kind_phys), intent(in)    :: sol(ncol,nlev,nspc)
    call set_rates( rxt_rates, sol, ncol )
  end subroutine set_rates_w

  subroutine imp_slv_inti_w()
    use trop_mam4_mo_imp_sol, only: imp_slv_inti
    call imp_slv_inti()
  end subroutine imp_slv_inti_w

  subroutine imp_sol_w( ncol, nlev, nspc, nrxt, nextfrc, ncls, base_sol, reaction_rates, &
                        het_rates, extfrc, delt, prod_out, loss_out, nfail_step, nfail_cell )
    use trop_mam4_mo_imp_sol, only: imp_sol
    integer,         intent(in)    :: ncol, nlev, nspc, nrxt, nextfrc, ncls
    real(kind_phys), intent(inout) :: base_sol(ncol,nlev,nspc)
    real(kind_phys), intent(in)    :: reaction_rates(ncol,nlev,nrxt)
    real(kind_phys), intent(in)    :: het_rates(ncol,nlev,nspc)
    real(kind_phys), intent(in)    :: extfrc(ncol,nlev,nextfrc)
    real(kind_phys), intent(in)    :: delt
    real(kind_phys), intent(out)   :: prod_out(ncol,nlev,ncls)
    real(kind_phys), intent(out)   :: loss_out(ncol,nlev,ncls)
    integer,         intent(out)   :: nfail_step, nfail_cell
    call imp_sol( base_sol, reaction_rates, het_rates, extfrc, delt, ncol, nlev, &
                  prod_out, loss_out, nfail_step, nfail_cell )
  end subroutine imp_sol_w

  subroutine exp_sol_w( ncol, nlev, nspc, nrxt, nextfrc, ncls, base_sol, reaction_rates, &
                        het_rates, extfrc, delt, ltrop, prod_out, loss_out )
    use trop_mam4_mo_exp_sol, only: exp_sol
    integer,         intent(in)    :: ncol, nlev, nspc, nrxt, nextfrc, ncls
    real(kind_phys), intent(inout) :: base_sol(ncol,nlev,nspc)
    real(kind_phys), intent(in)    :: reaction_rates(ncol,nlev,nrxt)
    real(kind_phys), intent(in)    :: het_rates(ncol,nlev,nspc)
    real(kind_phys), intent(in)    :: extfrc(ncol,nlev,nextfrc)
    real(kind_phys), intent(in)    :: delt
    integer,         intent(in)    :: ltrop(ncol)
    real(kind_phys), intent(out)   :: prod_out(ncol,nlev,ncls)
    real(kind_phys), intent(out)   :: loss_out(ncol,nlev,ncls)
    call exp_sol( base_sol, reaction_rates, het_rates, extfrc, delt, ncol, nlev, &
                  ltrop, prod_out, loss_out )
  end subroutine exp_sol_w

end module trop_mam4_chem_mechanism
