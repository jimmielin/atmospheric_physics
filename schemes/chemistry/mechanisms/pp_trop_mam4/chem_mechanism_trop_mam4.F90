module chem_mechanism_trop_mam4
!---------------------------------------------------------------------
! Generated by the CAM chemistry preprocessor (model = cam_sima). Do not edit.
! Register-only CCPP scheme for the trop_mam4 mechanism.
! The chem_mechanism namelist variable arrives as a CCPP argument (standard
! name gas_phase_chemistry_mechanism_name, owned by chem_mechanism_select).
! When it names this mechanism the
! scheme publishes the descriptor and returns the mechanism constituents;
! otherwise it returns no constituents, so a suite may list several
! mechanism packages and the namelist selects one at run time.
!---------------------------------------------------------------------

  implicit none
  private

  public :: chem_mechanism_trop_mam4_register

contains

!> \section arg_table_chem_mechanism_trop_mam4_register Argument Table
!! \htmlinclude chem_mechanism_trop_mam4_register.html
  subroutine chem_mechanism_trop_mam4_register( chem_mechanism, constituent_props, errmsg, errflg )
    use ccpp_constituent_prop_mod, only: ccpp_constituent_properties_t
    use chem_mechanism_mod,        only: chem_mechanism_activate
    use trop_mam4_chem_mechanism, only: trop_mam4_chem_mechanism_define

    character(len=*), intent(in)  :: chem_mechanism
    type(ccpp_constituent_properties_t), allocatable, intent(out) :: constituent_props(:)
    character(len=*), intent(out) :: errmsg
    integer,          intent(out) :: errflg

    errmsg = ''
    errflg = 0

    if( trim( chem_mechanism ) /= 'trop_mam4' ) then
       allocate( constituent_props(0) )
       return
    end if

    call chem_mechanism_activate( 'trop_mam4', trop_mam4_chem_mechanism_define, &
                                  constituent_props, errmsg, errflg )

  end subroutine chem_mechanism_trop_mam4_register

end module chem_mechanism_trop_mam4
